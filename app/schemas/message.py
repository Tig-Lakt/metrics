"""Схемы для эндпоинтов сообщений.

Почему отдельная схема, а не возврат модели БД напрямую:
    Модель Message из app/db/models.py — это модель ТАБЛИЦЫ. Если в
    будущем в неё добавится, например, поле internal_note или user_id,
    возврат модели напрямую из эндпоинта случайно "утечёт" наружу через
    API. Отдельная схема ответа явно фиксирует контракт API: наружу
    уходит ровно то, что здесь описано, и ничего больше.
"""

from pydantic import BaseModel


class MessageRead(BaseModel):
    """Публичное представление сообщения, отдаваемое клиенту API."""

    id: int
    text: str
